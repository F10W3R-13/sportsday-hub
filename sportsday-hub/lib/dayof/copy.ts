/** 항목 → 친절 설명. 없으면 undefined (원문만 표시). */
export function friendlyFor(item: ScheduleItem): string | undefined {
  if (item.source === 'game' && item.gameIdx !== undefined && item.role) {
    return GAME_ROLE_COPY[`${item.gameIdx}::${item.role}`]
  }
  for (const [kw, copy] of TASK_KEYWORD_COPY) {
    if (item.title.includes(kw)) return copy
  }
  return undefined
}

